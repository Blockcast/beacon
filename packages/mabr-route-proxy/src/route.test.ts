import test from 'node:test';
import assert from 'node:assert/strict';
import { createRouteMabrSession } from './route.ts';

function fakeWasm(mpd = '#EXTM3U\n# generated by SLS') {
  const memory = new WebAssembly.Memory({ initial: 18 });
  const input = 1024;
  const objects = [
    { toi: 1n, location: 'live/manifest.mpd', type: 'application/dash+xml', data: Uint8Array.from([60, 77, 80, 68, 62]) },
    { toi: 2n, location: 'live/master.m3u8', type: '', data: Uint8Array.from([35, 69, 88, 84, 77, 51, 85]) },
    { toi: 3n, location: 'live/seg-1.m4s', type: 'video/mp4', data: Uint8Array.from([0, 1, 2, 3]) },
  ];
  let index = 0;
  const encoder = new TextEncoder();
  const put = (offset: number, value: string | Uint8Array) => {
    const bytes = typeof value === 'string' ? encoder.encode(value) : value;
    new Uint8Array(memory.buffer, offset, bytes.byteLength).set(bytes);
    return bytes.byteLength;
  };
  const exports = {
    memory,
    route_get_buffer: () => input,
    route_get_buffer_size: () => 4096,
    route_process_udp: () => {},
    route_pop_completed_tsi: () => 7n,
    route_pop_completed_toi: () => objects[index]?.toi ?? 0n,
    route_pop_completed_len: () => objects[index]?.data.byteLength ?? 0,
    route_pop_completed_data: () => { put(2048, objects[index]?.data ?? new Uint8Array()); return 2048; },
    route_pop_completed_type: () => 3072,
    route_pop_completed_type_len: () => put(3072, objects[index]?.type ?? ''),
    route_pop_completed_location: () => 3200,
    route_pop_completed_location_len: () => put(3200, objects[index]?.location ?? ''),
    route_pop_completed_codepoint: () => 8,
    route_pop_completed_integrity: () => 100,
    route_pop_completed_advance: () => { index += 1; },
    route_get_mpd: () => { put(3400, mpd); return 3400; },
    route_get_mpd_len: () => mpd.length,
    route_get_mpd_location: () => { put(3500, 'live/generated.m3u8'); return 3500; },
    route_get_mpd_location_len: () => 'live/generated.m3u8'.length,
  };
  const process = () => {};
  exports.route_process_udp = process;
  exports.route_get_completed_count = () => index < objects.length ? objects.length - index : 0;
  return { exports, objects };
}

test('feeds ROUTE objects to DASH and HLS URLs and detaches cleanly', async () => {
  let listener: ((event: CustomEvent<ArrayBuffer>) => void) | undefined;
  let config: Record<string, unknown> | undefined;
  let unsubscribed = false;
  const gateway = {
    async subscribe(value: object) {
      config = value as Record<string, unknown>;
      return {
        addEventListener(_type: 'bytes', callback: (event: CustomEvent<ArrayBuffer>) => void) { listener = callback; },
        removeEventListener() { listener = undefined; },
        async unsubscribe() { unsubscribed = true; },
      };
    },
  };
  const wasm = fakeWasm();
  const manifestUrl = 'https://player.test/live/manifest.mpd';
  const session = createRouteMabrSession({
    gateway,
    wasm,
    group: '239.21.4.1',
    port: 5004,
    baseUrl: new URL('/', manifestUrl).href,
  });
  await session.start();
  assert.deepEqual(config, {
    origin: 'tuner', standard: 'atsc3', group: '239.21.4.1', port: 5004,
    consume: 'bytes', protocol: 'route',
  });
  listener?.({ detail: Uint8Array.of(1, 2).buffer } as CustomEvent<ArrayBuffer>);
  const mpd = await session.fetch(manifestUrl);
  const hls = await session.fetch('https://player.test/live/master.m3u8');
  const segment = await session.fetch('https://player.test/live/seg-1.m4s');
  const generatedHls = await session.fetch('https://player.test/live/generated.m3u8');
  assert.equal(mpd.headers.get('content-type'), 'application/dash+xml');
  assert.equal(hls.headers.get('content-type'), 'application/vnd.apple.mpegurl');
  assert.equal(segment.headers.get('content-type'), 'video/mp4');
  assert.equal(await generatedHls.text(), '#EXTM3U\n# generated by SLS');
  assert.equal((await hls.text()), '#EXTM3U');
  assert.equal(session.size, 4);
  await session.stop();
  assert.equal(unsubscribed, true);
  assert.equal(listener, undefined);
});

test('caps oversized SLS manifests to route.wasm result-buffer capacity', async () => {
  let listener: ((event: CustomEvent<ArrayBuffer>) => void) | undefined;
  const gateway = {
    async subscribe() {
      return {
        addEventListener(_type: 'bytes', callback: (event: CustomEvent<ArrayBuffer>) => void) { listener = callback; },
        removeEventListener() { listener = undefined; },
        async unsubscribe() {},
      };
    },
  };
  const session = createRouteMabrSession({
    gateway,
    wasm: fakeWasm('x'.repeat((1 << 20) + 64)),
    group: '239.21.4.1',
    port: 5004,
    baseUrl: 'https://player.test/',
  });
  await session.start();
  listener?.({ detail: Uint8Array.of(1).buffer } as CustomEvent<ArrayBuffer>);
  const response = await session.fetch('https://player.test/live/generated.m3u8');
  assert.equal((await response.arrayBuffer()).byteLength, 1 << 20);
  await session.stop();
});

test('does not claim an unsupported ATSC 1 tuner-origin subscription', async () => {
  const session = createRouteMabrSession({
    gateway: { async subscribe() { throw new Error('subscribe must not be called'); } },
    wasm: fakeWasm(),
    standard: 'atsc1',
  });
  await assert.rejects(session.start(), /ATSC1 raw MPEG-TS/);
});

